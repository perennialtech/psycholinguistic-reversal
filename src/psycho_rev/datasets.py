"""Unified dataclasses and dataset loaders for legacy and real-world LLM corpora.

Supports both the legacy hand-crafted splits in `psycho_rev.benchmark_data` and
JSONL-backed real-world datasets generated by `psycho_rev.corpus_builder`.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable, Mapping

from psycho_rev.benchmark_data import (
    HUMAN_CONTROL,
    HUMAN_CONTROL_MULTIPARA,
    IDENTITY_REGULARIZERS,
    MULTIPARA_BENCHMARK,
    TEST_BENCHMARK,
    TRAIN_DENSE_CORPUS,
    BenchmarkSample,
)

DEFAULT_DATASET_DIR = Path.home() / ".local" / "share" / "psycholinguistic-reversal" / "datasets"

LEGACY_SPLIT_NAMES: frozenset[str] = frozenset(
    {
        "test",
        "legacy_test",
        "human_control",
        "multipara",
        "human_control_multipara",
        "train_dense",
        "identity_regularizers",
        "all_legacy_test",
    }
)


@dataclass(frozen=True)
class DatasetSample:
    """A single prose passage from either a real-world LLM corpus or legacy benchmark."""

    sample_id: str
    domain: str
    text: str
    source_model: str = "legacy"
    prompt_id: str = ""
    split: str = ""
    is_out_of_lexicon: bool | None = None
    is_multipara: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.is_multipara and "\n\n" in self.text:
            object.__setattr__(self, "is_multipara", True)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "DatasetSample":
        known_keys = {
            "sample_id",
            "domain",
            "text",
            "source_model",
            "prompt_id",
            "split",
            "is_out_of_lexicon",
            "is_multipara",
            "metadata",
        }
        extra = {k: v for k, v in data.items() if k not in known_keys}
        meta = dict(data.get("metadata") or {})
        if extra:
            meta.update(extra)
        text = str(data["text"])
        is_multi = data.get("is_multipara")
        if is_multi is None:
            is_multi = "\n\n" in text
        ool = data.get("is_out_of_lexicon")
        return cls(
            sample_id=str(data["sample_id"]),
            domain=str(data["domain"]),
            text=text,
            source_model=str(data.get("source_model", "legacy")),
            prompt_id=str(data.get("prompt_id", "")),
            split=str(data.get("split", "")),
            is_out_of_lexicon=None if ool is None else bool(ool),
            is_multipara=bool(is_multi),
            metadata=meta,
        )

    @classmethod
    def from_benchmark_sample(
        cls,
        sample: BenchmarkSample,
        *,
        split: str = "test",
        source_model: str = "legacy",
    ) -> "DatasetSample":
        return cls(
            sample_id=sample.sample_id,
            domain=sample.domain,
            text=sample.text,
            source_model=source_model,
            prompt_id="",
            split=split,
            is_out_of_lexicon=None,
            is_multipara="\n\n" in sample.text,
            metadata={"legacy": True},
        )


@dataclass(frozen=True)
class DistilledPair:
    """A teacher-distilled rewrite pair with optional hard negatives for SFT / DPO / SimPO."""

    pair_id: str
    sample_id: str
    domain: str
    source: str
    chosen: str
    rejected: str = ""
    hard_negatives: list[dict[str, str]] = field(default_factory=list)
    is_identity: bool = False
    teacher_model: str = ""
    source_model: str = ""
    split: str = "train"
    is_out_of_lexicon: bool | None = None
    code_preservation_rate: float = 1.0
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "DistilledPair":
        known_keys = {
            "pair_id",
            "sample_id",
            "domain",
            "source",
            "chosen",
            "rejected",
            "hard_negatives",
            "is_identity",
            "teacher_model",
            "source_model",
            "split",
            "is_out_of_lexicon",
            "code_preservation_rate",
            "metadata",
        }
        extra = {k: v for k, v in data.items() if k not in known_keys}
        meta = dict(data.get("metadata") or {})
        if extra:
            meta.update(extra)
        ool = data.get("is_out_of_lexicon")
        raw_negs = data.get("hard_negatives") or []
        hard_negs: list[dict[str, str]] = [
            {"type": str(item.get("type", "unknown")), "text": str(item.get("text", ""))}
            for item in raw_negs
            if isinstance(item, Mapping) and item.get("text")
        ]
        return cls(
            pair_id=str(data["pair_id"]),
            sample_id=str(data.get("sample_id", data["pair_id"])),
            domain=str(data.get("domain", "mixed")),
            source=str(data["source"]),
            chosen=str(data["chosen"]),
            rejected=str(data.get("rejected", "")),
            hard_negatives=hard_negs,
            is_identity=bool(data.get("is_identity", False)),
            teacher_model=str(data.get("teacher_model", "")),
            source_model=str(data.get("source_model", "")),
            split=str(data.get("split", "train")),
            is_out_of_lexicon=None if ool is None else bool(ool),
            code_preservation_rate=float(data.get("code_preservation_rate", 1.0)),
            metadata=meta,
        )


def _serialize_record(record: DatasetSample | DistilledPair | Mapping[str, Any]) -> dict[str, Any]:
    if isinstance(record, (DatasetSample, DistilledPair)):
        return record.to_dict()
    if isinstance(record, Mapping):
        return dict(record)
    raise TypeError(f"Unsupported record type for JSONL serialization: {type(record)!r}")


def save_jsonl(
    path: str | Path,
    records: Iterable[DatasetSample | DistilledPair | Mapping[str, Any]],
    *,
    append: bool = False,
) -> int:
    """Write records to a UTF-8 JSONL file, creating parent directories if needed."""
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    mode = "a" if append else "w"
    count = 0
    with out_path.open(mode, encoding="utf-8") as fh:
        for record in records:
            payload = _serialize_record(record)
            fh.write(json.dumps(payload, ensure_ascii=False) + "\n")
            count += 1
        fh.flush()
    return count


def load_jsonl(path: str | Path, *, skip_corrupt: bool = False) -> list[dict[str, Any]]:
    """Load records from a UTF-8 JSONL file, optionally skipping truncated/corrupt lines."""
    in_path = Path(path)
    if not in_path.exists():
        return []
    records: list[dict[str, Any]] = []
    with in_path.open("r", encoding="utf-8") as fh:
        for line_no, raw_line in enumerate(fh, start=1):
            stripped = raw_line.strip()
            if not stripped:
                continue
            try:
                obj = json.loads(stripped)
            except json.JSONDecodeError as exc:
                if skip_corrupt:
                    continue
                raise ValueError(f"Invalid JSON on line {line_no} of {in_path}: {exc}") from exc
            if not isinstance(obj, dict):
                if skip_corrupt:
                    continue
                raise ValueError(f"Expected JSON object on line {line_no} of {in_path}")
            records.append(obj)
    return records


def _load_legacy_split(name: str) -> list[DatasetSample]:
    key = name.strip().lower()
    if key in {"test", "legacy_test"}:
        return [DatasetSample.from_benchmark_sample(s, split="test") for s in TEST_BENCHMARK]
    if key == "human_control":
        return [
            DatasetSample.from_benchmark_sample(s, split="human_control", source_model="human")
            for s in HUMAN_CONTROL
        ]
    if key == "multipara":
        return [DatasetSample.from_benchmark_sample(s, split="multipara") for s in MULTIPARA_BENCHMARK]
    if key == "human_control_multipara":
        return [
            DatasetSample.from_benchmark_sample(s, split="human_control_multipara", source_model="human")
            for s in HUMAN_CONTROL_MULTIPARA
        ]
    if key == "all_legacy_test":
        return [
            DatasetSample.from_benchmark_sample(s, split="test") for s in TEST_BENCHMARK
        ] + [
            DatasetSample.from_benchmark_sample(s, split="multipara") for s in MULTIPARA_BENCHMARK
        ]
    if key == "train_dense":
        return [
            DatasetSample(
                sample_id=f"train_dense_{idx:03d}",
                domain="mixed",
                text=text,
                source_model="legacy",
                split="train",
                is_multipara="\n\n" in text,
                metadata={"legacy": True},
            )
            for idx, text in enumerate(TRAIN_DENSE_CORPUS, start=1)
        ]
    if key == "identity_regularizers":
        return [
            DatasetSample(
                sample_id=f"identity_{idx:03d}",
                domain="human_control",
                text=text,
                source_model="human",
                split="train",
                is_multipara="\n\n" in text,
                metadata={"legacy": True, "is_identity": True},
            )
            for idx, text in enumerate(IDENTITY_REGULARIZERS, start=1)
        ]
    raise ValueError(
        f"Unknown legacy split {name!r}. Expected one of {sorted(LEGACY_SPLIT_NAMES)} or a JSONL path."
    )


def _resolve_split_jsonl(path: Path, split: str | None) -> Path:
    if path.is_file():
        return path
    if path.is_dir():
        candidates = (
            [path / f"{split}.jsonl"]
            if split
            else [
                path / "test_ood.jsonl",
                path / "test.jsonl",
                path / "val.jsonl",
                path / "train.jsonl",
                path / "raw_corpus.jsonl",
            ]
        )
        for cand in candidates:
            if cand.exists():
                return cand
        raise FileNotFoundError(
            f"No matching JSONL split file found in directory {path} (requested split={split!r})."
        )
    raise FileNotFoundError(f"Dataset path does not exist: {path}")


def load_eval_split(
    split_or_path: str | Path,
    *,
    split: str | None = None,
    domain: str | None = None,
    out_of_lexicon_only: bool = False,
    limit: int | None = None,
) -> list[DatasetSample]:
    """Load an evaluation or corpus split from either legacy `benchmark_data` or JSONL.

    Args:
        split_or_path: Legacy split name (e.g. ``"test"``, ``"multipara"``, ``"human_control"``),
            a path to a ``.jsonl`` file, or a dataset directory containing ``<split>.jsonl``.
        split: Optional split filename stem when ``split_or_path`` is a directory (e.g. ``"test_ood"``).
        domain: Optional domain filter (e.g. ``"coding"``, ``"technical_docs"``, ``"essay"``, ``"workplace_chat"``).
        out_of_lexicon_only: If True, keep only samples tagged ``is_out_of_lexicon is True``.
        limit: Optional maximum number of samples to return.
    """
    if isinstance(split_or_path, str) and split_or_path.strip().lower() in LEGACY_SPLIT_NAMES and not Path(split_or_path).exists():
        samples = _load_legacy_split(split_or_path)
    else:
        resolved = _resolve_split_jsonl(Path(split_or_path), split)
        raw_rows = load_jsonl(resolved)
        samples = [DatasetSample.from_dict(row) for row in raw_rows]

    if domain is not None:
        target_domain = domain.strip().lower()
        samples = [s for s in samples if s.domain.lower() == target_domain]
    if out_of_lexicon_only:
        samples = [s for s in samples if s.is_out_of_lexicon is True]
    if limit is not None:
        samples = samples[: max(limit, 0)]
    return samples


def load_distilled_pairs(
    path: str | Path,
    *,
    domain: str | None = None,
    split: str | None = None,
    include_identity: bool = True,
    require_rejected: bool = False,
    limit: int | None = None,
) -> list[DistilledPair]:
    """Load teacher-distilled training pairs from a JSONL file or dataset directory."""
    in_path = Path(path)
    if in_path.is_dir():
        candidates = [
            in_path / "distilled_pairs.jsonl",
            in_path / "train_pairs.jsonl",
            in_path / "pairs.jsonl",
        ]
        resolved = next((c for c in candidates if c.exists()), None)
        if resolved is None:
            raise FileNotFoundError(f"No distilled pairs JSONL found in {in_path}")
    elif in_path.exists():
        resolved = in_path
    else:
        raise FileNotFoundError(f"Distilled pairs file does not exist: {in_path}")

    pairs = [DistilledPair.from_dict(row) for row in load_jsonl(resolved)]

    if domain is not None:
        target_domain = domain.strip().lower()
        pairs = [p for p in pairs if p.domain.lower() == target_domain]
    if split is not None:
        target_split = split.strip().lower()
        pairs = [p for p in pairs if p.split.lower() == target_split]
    if not include_identity:
        pairs = [p for p in pairs if not p.is_identity]
    if require_rejected:
        pairs = [p for p in pairs if bool(p.rejected.strip())]
    if limit is not None:
        pairs = pairs[: max(limit, 0)]
    return pairs
